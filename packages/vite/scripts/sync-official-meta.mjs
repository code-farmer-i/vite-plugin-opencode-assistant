import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
// 从脚本位置往上找到 vite 包（package.json name === vite-plugin-aipanel），不依赖调用 cwd
function findViteRoot() {
  let dir = path.dirname(fileURLToPath(import.meta.url));
  for (;;) {
    const pj = path.join(dir, "package.json");
    if (fs.existsSync(pj)) {
      try {
        const p = JSON.parse(fs.readFileSync(pj, "utf8"));
        if (p.name === "vite-plugin-aipanel") return dir;
      } catch {
        /* 忽略不合格 package.json */
      }
    }
    const parent = path.dirname(dir);
    if (parent === dir) throw new Error("cannot locate vite-plugin-aipanel package");
    dir = parent;
  }
}
const viteRoot = findViteRoot();
const pkgPath = require.resolve("chrome-devtools-mcp/package.json");
const toolsDir = path.join(path.dirname(pkgPath), "build", "src", "tools");
const SQ = String.fromCharCode(39);
const files = fs.readdirSync(toolsDir).filter((f) => f.endsWith(".js") && !f.startsWith("slim"));
const meta = [];
for (const f of files) {
  const src = fs.readFileSync(path.join(toolsDir, f), "utf8");
  for (const sec of src.split("export const ").slice(1)) {
    const nameMatch = sec.match(new RegExp("name: " + SQ + "([a-z_0-9]+)" + SQ));
    if (!nameMatch) continue;
    const cat = (sec.match(/category: ToolCategory\.([A-Z_]+)/) || [])[1] || "";
    const ro = (sec.match(/readOnlyHint:\s*(true|false)/) || [])[1] || "false";
    const page = /definePageTool/.test(sec);
    const conds = [];
    const cm = sec.match(/conditions:\s*\[([^\]]*)\]/);
    if (cm) {
      const condRe = new RegExp(SQ + "([a-zA-Z0-9_]+)" + SQ, "g");
      let m;
      while ((m = condRe.exec(cm[1])) !== null) conds.push(m[1]);
    }
    meta.push({ name: nameMatch[1], category: cat, readOnlyHint: ro === "true", pageScoped: page, conditions: conds });
  }
}
meta.sort((a, b) => a.name.localeCompare(b.name));
const header = "/** AUTO-GENERATED by packages/vite/scripts/sync-official-meta.mjs (build) \u2014 \u4e0d\u624b\u6539\uff1b\u5347\u7ea7 chrome-devtools-mcp \u540e\u91cd\u8dd1\u6784\u5efa\u5373\u53ef\u3002 */";
const lines = [
  header,
  "export interface OfficialToolMeta {",
  "  name: string;",
  '  category: "INPUT" | "NAVIGATION" | "EMULATION" | "PERFORMANCE" | "NETWORK" | "DEBUGGING" | "EXTENSIONS" | "THIRD_PARTY" | "MEMORY" | "WEBMCP" | "PWA" | "";',
  "  readOnlyHint: boolean;",
  "  pageScoped: boolean;",
  "  conditions: string[];",
  "}",
  "",
  "export const OFFICIAL_TOOL_META: OfficialToolMeta[] = [",
  ...meta.map((m) => `  { name: ${JSON.stringify(m.name)}, category: ${JSON.stringify(m.category)}, readOnlyHint: ${m.readOnlyHint}, pageScoped: ${m.pageScoped}, conditions: ${JSON.stringify(m.conditions)} },`),
  "];",
  "",
].join(String.fromCharCode(10));
const out = path.join(viteRoot, "src/core/official-meta.ts");
fs.writeFileSync(out, lines);
console.log("[sync-official-meta] generated", meta.length, "tools ->", path.relative(viteRoot, out));